// @ts-check
/**
 * The "For AI agents" pointer every docs page carries, in both of its forms:
 *
 *   - HTML: rendered at the top of `<main>` by `src/components/CustomBanner.astro`.
 *   - Markdown: inserted under the H1 of every `<page>.md` twin after the build,
 *     by `markdownAgentHintIntegration()` below.
 *
 * An agent that lands on a single page — from search, a citation, or a pasted
 * link — otherwise has no way to learn that `/llms.txt` or the page's Markdown
 * twin exists. `<link rel="alternate">` in `<head>` covers crawlers that read
 * it; this line covers agents that only read the page text.
 *
 * Both forms read their wording from here so they cannot drift apart.
 */
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

/** The documentation index emitted by `starlight-llms-txt`. */
export const LLMS_TXT_PATH = '/llms.txt';

/** Lead-in shared by the HTML and Markdown forms. */
export const AGENT_INDEX_LEAD = 'For AI agents: a documentation index is available at';

/**
 * The Markdown twin for a page URL, following the convention
 * `@ekline/starlight-contextual-menu` uses (`tests/markdown-twins.test.mjs`):
 * `/` → `/index.md`, `/foo/bar/` → `/foo/bar.md`.
 *
 * @param {string} pathname
 */
export function markdownTwinPath(pathname) {
	const trimmed = pathname.replace(/\/index\.html$/, '').replace(/\.html$/, '').replace(/\/+$/, '');
	return trimmed === '' ? '/index.md' : `${trimmed}.md`;
}

/**
 * The line as it appears in a Markdown twin. Uses the absolute URL: a twin is
 * often read on its own, outside the site, where a root-relative path has
 * nothing to resolve against.
 *
 * @param {string | URL | undefined} site
 */
export function markdownAgentHint(site) {
	const url = site ? new URL(LLMS_TXT_PATH, site).href : LLMS_TXT_PATH;
	return `> ${AGENT_INDEX_LEAD} ${url}`;
}

/**
 * Insert the hint directly under the leading `# ` heading, or at the very top
 * when there is none. The twin keeps starting with its H1, which
 * `tests/markdown-twins.test.mjs` requires. Running it twice changes nothing.
 *
 * @param {string} markdown
 * @param {string} hint
 */
export function withAgentHint(markdown, hint) {
	if (markdown.includes(hint)) return markdown;
	if (!markdown.startsWith('# ')) return `${hint}\n\n${markdown}`;

	const end = markdown.indexOf('\n');
	if (end === -1) return `${markdown}\n\n${hint}\n`;
	const heading = markdown.slice(0, end);
	const rest = markdown.slice(end + 1).replace(/^\n+/, '');
	return `${heading}\n\n${hint}\n\n${rest}`;
}

/** @param {string} dir */
async function* walkMarkdown(dir) {
	for (const entry of await readdir(dir, { withFileTypes: true })) {
		const path = join(dir, entry.name);
		if (entry.isDirectory()) yield* walkMarkdown(path);
		else if (entry.name.endsWith('.md')) yield path;
	}
}

/**
 * Astro integration: after the build, add the hint to every `.md` file in the
 * output.
 *
 * Post-processing the output rather than the route: the twins are generated by
 * `@ekline/starlight-contextual-menu`, which has no option to prepend text, and
 * every `.md` file in `dist/` is one of those twins (`public/` ships none).
 * Register it after `starlight()` so it runs once every route is written.
 *
 * Build-only: `astro dev` serves the twins without the line.
 *
 * @returns {import('astro').AstroIntegration}
 */
export function markdownAgentHintIntegration() {
	/** @type {string | undefined} */
	let site;
	return {
		name: 'markdown-agent-hint',
		hooks: {
			'astro:config:done': ({ config }) => {
				site = config.site;
			},
			'astro:build:done': async ({ dir, logger }) => {
				const hint = markdownAgentHint(site);
				let updated = 0;
				for await (const file of walkMarkdown(fileURLToPath(dir))) {
					const source = await readFile(file, 'utf-8');
					const output = withAgentHint(source, hint);
					if (output === source) continue;
					await writeFile(file, output);
					updated++;
				}
				logger.info(`Added the ${LLMS_TXT_PATH} pointer to ${updated} Markdown pages.`);
			},
		},
	};
}
